async function sendQQMarkdown(_ctx, session, content, musicLogger) {
    try {
        await session.bot.internal.sendMessage(session.channelId, {
            msg_id: session.messageId,
            msg_type: 2,
            markdown: {
                content: content
            }
        });
        return true;
    } catch (error) {
        musicLogger?.logInfo('⚠️ QQ Markdown 发送失败', summarizeError(error));
        musicLogger?.logDebug('QQ Markdown 发送异常', error);
        return false;
    }
}


async function sendQQMarkdown(ctx, session, content) {
    try {
        await session.bot.internal.sendMessage(session.channelId, {
            msg_id: session.messageId,
            msg_type: 2,
            markdown: {
                content: content
            }
        });
        return true;
    } catch (error) {
        ctx.logger.error('发送 QQ Markdown 失败:', error);
        return false;
    }
}


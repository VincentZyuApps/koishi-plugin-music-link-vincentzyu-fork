"use strict";

function formatDuration(ms) {
    if (!ms || ms <= 0) return '-';
    const totalSeconds = Math.floor(ms / 1000);
    const minutes = Math.floor(totalSeconds / 60);
    const seconds = totalSeconds % 60;
    return `${minutes}:${seconds.toString().padStart(2, '0')}`;
}

function getArtistDisplay(artist) {
    if (!artist) return '未知';
    if (Array.isArray(artist)) {
        return artist.map(a => a.name || a).join(', ');
    }
    return artist;
}

function renderSongListMarkdownTable(songList, config = {}) {
    if (!songList || !Array.isArray(songList) || songList.length === 0) {
        return '';
    }

    const maxDisplay = config.maxDisplay || 10;
    const displayList = songList.slice(0, maxDisplay);
    const waitTimeout = config.waitTimeout || 45;
    const atRobotText = config.atRobotText || "@机器人";
    const exitCommands = config.exitCommand ? config.exitCommand.split(/[,，]/).map(cmd => cmd.trim()) : ['0', '不听了'];
    const showExitTip = config.menuExitCommandTip !== false;

    let md = `# 🎵 歌单列表\n\n`;

    // 添加渲染信息（如果启用）
    if (config.showRenderInfo) {
        const version = config.version || 'unknown';
        const repositoryUrl = config.repositoryUrl || '';
        const dateTime = new Date().toISOString();
        
        md += `> generated by koishi plugin: music-link-vincentzyu-fork\n`;
        md += `> version: ${version}\n`;
        md += `> date_time: ${dateTime}\n`;
        if (repositoryUrl) {
            md += `> repo_url: ${repositoryUrl}\n`;
        }
        md += `\n`;
    }

    md += `| # | 歌曲名称 | 歌手 | 时长 |\n`;
    md += `|---|---------|------|-----|\n`;

    displayList.forEach((song, index) => {
        const name = song.name || song.song || '未知';
        const artist = song.artists || song.artist || song.ar || song.singer || '未知';
        const duration = formatDuration(song.duration);
        
        md += `| ${index + 1} | ${name} | ${getArtistDisplay(artist)} | ${duration} |\n`;
    });

    md += `\n> 共 ${songList.length} 首歌曲，显示前 ${maxDisplay} 首\n`;

    md += `\n---\n\n`;
    if (showExitTip) {
        md += `#### 退出选择请发 @机器人 + [${exitCommands}] 中的任意内容\n\n`;
    }
    md += `> ⏰ 请在 ${waitTimeout} 秒内，\n> 输入歌曲对应的序号:\n> ➣示例：${atRobotText} 1\n`;

    return md;
}

